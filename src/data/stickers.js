/** Genera el ID de figurita de un equipo: ej. MEX_0, MEX_11 */
export const teamStickerId = (teamCode, index) => `${teamCode}_${index}`

/** Genera el array de sticker objects de un equipo */
export const getTeamStickers = (team) =>
  team.players.map((name, i) => ({
    id: teamStickerId(team.code, i),
    num: i,
    name,
    foil: i === 0, // index 0 siempre es FOIL
  }))

/** Lista plana de TODOS los IDs de figuritas (633 total) */
export const ALL_STICKER_IDS = [
  ...GROUPS.flatMap(g => g.teams.flatMap(t => t.players.map((_, i) => teamStickerId(t.code, i)))),
  ...SPECIAL_SECTIONS.flatMap(s => s.stickers.map(s => s.id)),
]

/** Mapa rápido de equipo por code */
export const TEAM_BY_CODE = Object.fromEntries(
  GROUPS.flatMap(g => g.teams.map(t => [t.code, { ...t, group: g.letter }]))
)
